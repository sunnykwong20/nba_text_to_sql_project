from pydantic import BaseModel, Field

#Script of prompts and all prompt related functions

############# For Node 1: Identify Schema

class SchemaLinkingResult(BaseModel):
    tables: list[str] = Field(description="Names of tables needed to answer the question")
    variables: list[str] = Field(description="Names of columns needed to answer the question")
    response_format: str = Field(description="Whether the question elicits a Table or a Narrative as the final response")


SCHEMA_LINKING_PROMPT = """You are given the schema of a SQLite database (as CREATE TABLE statements) and a user's question.

Schema:
{schema}

Question:
{question}

Identify exactly which tables and which columns are needed to answer this question. Only include tables/columns that are actually necessary.

You will also determine whether the user's question is asking for a table or a narrative. """


################## For Node 2: Generate SQL

generate_sql_prompt_no_error = """You are given the schema of a SQLite database necessary to complete your task, a user's question, and a list of variables.

Schema:
{schema}

Question:
{question}

Varables: 
{variables}

Produce a SQL lite query that will answer the users question. """

generate_sql_prompt_error = """You are given the schema of a SQLite database necessary to complete your task, a user's question, a list of variables, an error message, and an attempt of the SQL lite query.

Schema:
{schema}

Question:
{question}

Variables: 
{variables}

error: 
{error}

query:
{query}

Fix the sql lite query to make sure it answers the user question. """

class GenerateSQLResult(BaseModel):
    sql: str = Field(description="SQL query that is generated by LLM")


############# For Node 4: Format Response

format_response_prompt = """You are given a user's question and a resulting dataset.


Question:
{question}

result: 
{result}

Generate a appropriate response to the question using what is show in the result. """

class FormatResponseResult(BaseModel):
    response: str = Field(description="The human friend response to the question posed by the user")


############# For Evalulation layer: Checking if truth of AI generated result matches truth of What I put

narrative_correct_prompt = """You will receive the question, a ground truth statement of the answer, and the
agent response to the question. You are checking if the response of the AI agent response to factually correct
compared to the ground truth statement of the Answer. You are NOT grading writing quality, tone, or phrasing - only 
whether the facts agree.


Question Asked:
{question}

Ground Truth Statement: 
{ground_truth}

AI Agent Statement (To be graded): 
{agent_statement}

Check whether the facts of the AI Agent Statement states the same fact as the reference answer - same 
numbers, names, and conclusions. 

- if the AI agent states something that contradicts or isn't supported by the reference answer, that's unfaithful
- Different wording, extra context not in the reference, or a different sentence structure is fine and should NOT count
against faithfulness

"""

class NarrativeCorrectResult(BaseModel):
    is_correct: bool = Field(description="Boolean that states whether the AI agent statement factually matches the ground truth statement.")
    comment: str = Field(description = "Explanation of the verdict - why the statement matches or why it does not match the ground truth")
