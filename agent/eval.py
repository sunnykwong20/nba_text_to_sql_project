## Check 1: Checks for situations where the agent should refuse to try to make a query
def refuse_check(run, example) -> (dict | None):
    if example.metadata['response_format'] != 'out_of_scope':
        return None # This is not applicable, return None
    return {"key":"refuse_check","score":run.outputs['error'] is not None}


## Check 2: Checks for situation that it is supposed to return a table
def table_check(run, example) -> bool:
    if example.metadata['response_format'] != 'table':
        return None # This is not applicable, return None
    run_df = pd.DataFrame(run.outputs['result'])
    run_df = run_df.sort_values(by=sorted(list(run_df.columns))).reset_index(drop=True)
    example_df = pd.DataFrame(example.outputs['data_table'])
    example_df = example_df.sort_values(by=sorted(list(example_df.columns))).reset_index(drop=True)

    ### Check for columns
    run_cols = set(run_df.columns) 
    example_cols = set(example_df.columns)

    ### Gets the quicker checks out of the way before doing the more intensive tests
    if run_df.shape != example_df.shape:
        ## if the shape is not exactly the same, it is not a match
        return {"key":"table_check","score":False, "comment": "Data Frame Shapes are not the same"}
    elif run_cols != example_cols: 
        ## if the columns are not the same, it is not a match
        return {"key":"table_check","score":False, "comment": "Column Names are not the Same"}
    else:
        try:
            ## checks for exact match between row values
            pd.testing.assert_frame_equal(run_df, example_df, check_exact=False, check_like=True, check_dtype=False)
            return {"key":"table_check","score":True}
        except AssertionError as e:
            return {"key":"table_check","score":False, "comment": "Rows are not the same"}

## Check 3: Checks if narrative generated by AI is factually correct compared to the ground truth statement
def narrative_correct_check(run, example):
    if example.metadata['response_format'] != 'narrative':
        return None # This is not applicable, return None
    run_statement = run.outputs['response']
    example_statement = example.outputs['conversational_answer']
    question = example.inputs['question']

    prompt = narrative_correct_prompt.format(question=question, ground_truth = example_statement, agent_statement = run_statement)
    verdict = judge_llm.with_structured_output(NarrativeCorrectResult).invoke(prompt)

    return {"key":"narrative_correct_check","score":verdict.is_correct,"comment":verdict.comment}

def run_agent(inputs: dict) -> dict:
    final_state = graph.invoke({
        "question": inputs["question"],
        "sql": None,
        "tables": [],
        "variables": [],
        "result": None,
        "error": None,
        "attempts": 0,
        "response_format": None,
        "response": None,
    })
    return final_state

results = evaluate(
    run_agent,
    data = dataset_name,
    evaluators = [table_check, refuse_check, narrative_correct_check],
    experiment_prefix = "Baseline",
)